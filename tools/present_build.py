#!/usr/bin/env python3
"""Turn one markdown script into the data files a presenter app runs on.

Written 2026-11-06, the afternoon of a BISC presentation that went badly
because its presenter window was hand-built that morning and still being
changed while he sat in the room. Everything the window needs was known the
night before. Nothing assembled it, so it got assembled live.

Reads the format in templates/present/SCRIPT-FORMAT.md and writes
lib/beats.ts and lib/drill.ts. Deliberately does not write lib/scenes.tsx:
drawings are specific to the talk and inventing them is how figures end up
looking generated.

Usage: present_build.py <script.md> <out-dir> [--level script|sentence|bullets]
"""
from __future__ import annotations

import html
import json
import re
import sys
from pathlib import Path

LEVELS = ("script", "sentence", "bullets")


class Beat:
    def __init__(self, cue: str) -> None:
        self.cue = cue
        self.say = ""
        self.see = ""
        self.fill: list[str] = []


class Scene:
    def __init__(self, key: str, label: str) -> None:
        self.key = key
        self.label = label
        self.beats: list[Beat] = []


def parse(md: str) -> tuple[str, str, list[Scene], list[tuple[str, str]]]:
    title, who = "", ""
    scenes: list[Scene] = []
    qa: list[tuple[str, str]] = []
    scene: Scene | None = None
    beat: Beat | None = None
    in_qa = False
    q: str | None = None
    a: list[str] = []

    def flush_q() -> None:
        nonlocal q, a
        if q is not None:
            qa.append((q, " ".join(a).strip()))
        q, a = None, []

    for raw in md.splitlines():
        line = raw.rstrip()
        if line.startswith("# "):
            head = line[2:].strip()
            title, _, who = (p.strip() for p in head.partition("|"))
            continue
        if line.startswith("## "):
            flush_q()
            head = line[3:].strip()
            if head.lower() in ("q&a", "questions", "question prep"):
                in_qa, scene, beat = True, None, None
                continue
            in_qa = False
            key, _, label = (p.strip() for p in head.partition(":"))
            if not label:
                label = key
            key = re.sub(r"[^a-z0-9]+", "", key.lower()) or f"scene{len(scenes)}"
            scene = Scene(key, label)
            scenes.append(scene)
            beat = None
            continue
        if line.startswith("### "):
            head = line[4:].strip()
            if in_qa:
                flush_q()
                q = head
                continue
            if scene is None:
                scene = Scene(f"scene{len(scenes)}", "Untitled")
                scenes.append(scene)
            beat = Beat(head)
            scene.beats.append(beat)
            continue
        if not line.strip():
            continue
        if in_qa:
            a.append(line.strip())
            continue
        if beat is None:
            continue
        if line.lstrip().startswith(">"):
            beat.see = (beat.see + " " + line.lstrip()[1:].strip()).strip()
        elif line.lstrip().startswith("- "):
            beat.fill.append(line.lstrip()[2:].strip())
        else:
            beat.say = (beat.say + " " + line.strip()).strip()
    flush_q()
    return title, who, scenes, qa


def md_inline(s: str) -> str:
    """The sentence carries bold and italic into the presenter window.

    Escaped first, so the only tags in the result are the ones generated here.
    Without this, anything angle-bracketed in his script reached the presenter
    window through dangerouslySetInnerHTML, which is the kit's own
    security.md line about never passing raw content to that prop.
    """
    s = html.escape(s, quote=True)
    s = re.sub(r"\*\*(.+?)\*\*", r"<b>\1</b>", s)
    s = re.sub(r"(?<!\*)\*([^*]+?)\*(?!\*)", r"<i>\1</i>", s)
    return s


def clip(s: str, n: int) -> str:
    """Cut at a word boundary. The first version ended one prompt on
    "breakin", which is worse than no prompt when he is reading it mid-answer."""
    if len(s) <= n:
        return s
    cut = s[:n].rsplit(" ", 1)[0]
    return cut.rstrip(" ,;:") + "..."


def ts(value) -> str:
    return json.dumps(value, ensure_ascii=False)


def write_beats(path: Path, title: str, who: str, scenes: list[Scene]) -> None:
    keys = [s.key for s in scenes]
    out = [
        "// Generated by `chewbacca present` from the talk's script file.",
        "// Edit the script and rebuild rather than editing this by hand.",
        "",
        "export type State = Record<string, number>;",
        "export type Beat = { s: State; cue: string; say: string; see: string; fill: string[] };",
        f"export type SceneKey = {' | '.join(ts(k) for k in keys) or 'string'};",
        "",
        f"export const TITLE = {ts(title)};",
        f"export const PRESENTER = {ts(who)};",
        "",
        "export const BEATS: Record<SceneKey, Beat[]> = {",
    ]
    for sc in scenes:
        out.append(f"  {sc.key}: [")
        for i, b in enumerate(sc.beats):
            # One state value per beat, counting up. A hand-written scene reads
            # it as "how far through am I" and draws accordingly.
            state = ts({"step": i, "of": max(1, len(sc.beats) - 1)})
            out.append(
                f"    {{ s: {state}, cue: {ts(b.cue)}, say: {ts(md_inline(b.say))}, "
                f"see: {ts(b.see)}, fill: {ts(b.fill)} }},"
            )
        out.append("  ],")
    out += [
        "};",
        "",
        "export const ORDER: SceneKey[] = [" + ", ".join(ts(k) for k in keys) + "];",
        "",
        "export const LABEL: Record<string, string> = {",
    ]
    for sc in scenes:
        out.append(f"  {sc.key}: {ts(sc.label)},")
    out += [
        "};",
        "",
        "export const SCRIPT: Record<string, string> = {",
    ]
    for sc in scenes:
        block = " ".join(b.say for b in sc.beats if b.say).strip()
        # The scene block is read aloud, so it carries neither HTML nor the
        # markdown stars. The first version left "**hemoglobin**" in the text
        # he would have been reading from.
        block = re.sub(r"<[^>]+>", "", block)
        block = re.sub(r"\*{1,2}([^*]+?)\*{1,2}", r"\1", block)
        out.append(f"  {sc.key}: {ts(block)},")
    out += [
        "};",
        "",
        "export type Row = { scene: string; beat: number | null; beats: number;"
        " cue: string; see: string; say: string; fill: string[] };",
        "",
        "export const ROWS: Row[] = ORDER.flatMap((name): Row[] =>",
        "  BEATS[name].map((b, i) => ({",
        "    scene: name, beat: i, beats: BEATS[name].length,",
        "    cue: b.cue, see: b.see, say: b.say, fill: b.fill,",
        "  })),",
        ");",
        "",
        "// Where he should be by each stop, spread evenly across the window.",
        "// A per-scene pace is better once he has run it; this is the start.",
        "export const CAMERA: Record<SceneKey, [number, number, number, number][]> = {",
    ]
    for sc in scenes:
        frames = ", ".join("[0, 0, 1600, 900]" for _ in sc.beats)
        out.append(f"  {sc.key}: [{frames}],")
    out += ["};", ""]

    # The talk page also needs where to put the figure, what colour the board
    # is, and which beats are a number held on its own. The first generated
    # app did not compile without these: "The export SLOT was not found".
    out += [
        "// Where the figure sits on the 1600x900 board. Measure it per scene",
        "// once the drawing exists; this is a sane frame to start from.",
        "export const SLOT: Record<string, [number, number, number, number]> = {",
        "  default: [56, 158, 1488, 464],",
    ]
    for sc in scenes:
        out.append(f"  {sc.key}: [56, 158, 1488, 464],")
    out += [
        "};",
        "",
        "// The lit background behind each scene.",
        "export const GROUND: Record<string, string> = {",
        "  cover: \"var(--canvas)\",",
    ]
    for sc in scenes:
        out.append(f"  {sc.key}: \"var(--canvas)\",")
    out += [
        "};",
        "",
        "// Beats where one number IS the slide. Key is \"scene:beatIndex\".",
        "// Add them once he knows which numbers carry the room.",
        "export const BIG: Record<string, { n: string; u: string; tone: string }> = {};",
        "",
    ]
    path.write_text("\n".join(out) + "\n")


def write_drill(path: Path, qa: list[tuple[str, str]], scenes: list[Scene]) -> None:
    # The nine facts default to the first bullet of each scene's opening beat,
    # which is a starting point he edits, not a claim that these are the nine
    # that matter.
    cold = []
    for sc in scenes:
        for b in sc.beats:
            if b.fill:
                cold.append((b.cue[:28], b.fill[0]))
                break
    # The chain is the talk explained one beat at a time, each card showing the
    # real figure from that beat. He learns off the same picture he will stand
    # next to, so the teaching cannot drift away from the talk.
    chain = []
    for sc in scenes:
        for i, b in enumerate(sc.beats):
            chain.append({
                "scene": sc.key, "beat": i,
                "t": b.cue[:1].upper() + b.cue[1:],
                "body": re.sub(r"<[^>]+>", "", b.say) or b.see,
                "note": "; ".join(b.fill[:2]),
            })

    out = [
        "// Generated by `chewbacca present` from the talk's script file.",
        "",
        "import type { SceneKey } from \"@/lib/beats\";",
        "",
        "export type ChainCard = {",
        "  t: string; body: string; note?: string; scene?: SceneKey; beat?: number;",
        "};",
        "",
        "// Each card carries the real drawing from its beat.",
        "export const CHAIN: ChainCard[] = [",
        *[
            f"  {{ scene: {ts(c['scene'])}, beat: {c['beat']}, t: {ts(c['t'])}, "
            f"body: {ts(c['body'])}, note: {ts(c['note'])} }},"
            for c in chain
        ],
        "];",
        "",
        "export const QA: [string, string][] = [",
        *[f"  [{ts(q)}, {ts(a)}]," for q, a in qa],
        "];",
        "",
        "// Short enough to read in the two seconds after someone asks.",
        "export const QPREP: [string, string][] = [",
        *[f"  [{ts(q)}, {ts(clip(a, 110))}]," for q, a in qa],
        "];",
        "",
        "// The facts that have to arrive without the script.",
        "export const COLD: [string, string][] = [",
        *[f"  [{ts(k)}, {ts(v)}]," for k, v in cold],
        "];",
        "",
    ]
    path.write_text("\n".join(out) + "\n")


def main() -> int:
    args = sys.argv[1:]
    level = "script"
    if "--level" in args:
        i = args.index("--level")
        level = args[i + 1] if i + 1 < len(args) else "script"
        del args[i : i + 2]
    if level not in LEVELS:
        print(f"present_build: --level must be one of {', '.join(LEVELS)}", file=sys.stderr)
        return 2
    if len(args) != 2:
        print(__doc__.strip().splitlines()[-1], file=sys.stderr)
        return 2

    script, out_dir = Path(args[0]), Path(args[1])
    if not script.is_file():
        print(f"present_build: no script at {script}", file=sys.stderr)
        return 1
    title, who, scenes, qa = parse(script.read_text())
    if not scenes:
        print("present_build: the script has no scenes. See SCRIPT-FORMAT.md", file=sys.stderr)
        return 1

    lib = out_dir / "lib"
    lib.mkdir(parents=True, exist_ok=True)
    write_beats(lib / "beats.ts", title, who, scenes)
    write_drill(lib / "drill.ts", qa, scenes)
    (lib / "level.ts").write_text(
        "// The aid level comes from how much he has rehearsed OUT LOUD.\n"
        "// skills/presenting/SKILL.md says why this is not his to pick on the day.\n"
        f"export const LEVEL = {ts(level)} as const;\n"
    )

    beats = sum(len(s.beats) for s in scenes)
    words = sum(len(re.sub(r"<[^>]+>", "", b.say).split()) for s in scenes for b in s.beats)
    print(f"scenes: {len(scenes)}  beats: {beats}  questions: {len(qa)}")
    print(f"spoken words: {words}  ({words / 140:.1f} min at 140wpm, {words / 160:.1f} at 160)")
    if words and not 8 * 140 <= words <= 10 * 140:
        where = "under" if words < 8 * 140 else "over"
        print(f"  NOTE: {where} a typical 8-to-10 minute window at a normal pace")
    missing = [b.cue for s in scenes for b in s.beats if not b.see]
    if missing:
        print(f"  {len(missing)} beat(s) have no 'on screen' line, so he will be guessing:")
        for c in missing[:5]:
            print(f"    - {c}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
