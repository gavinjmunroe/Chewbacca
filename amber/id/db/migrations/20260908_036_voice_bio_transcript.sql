-- THE VOICE BIO'S TRANSCRIPT.
--
-- "It should be a nice mic icon that transcribes what it says underneath." The
-- clip already plays; what it SAYS was never stored, so the profile offered a
-- waveform and no way to know whether it was worth 40 seconds of listening --
-- and a bio nobody plays is a bio nobody has.
--
-- The transcript comes from the same on-device transcription the recorder
-- already produces for every voice note in the app (the recorder hands it back
-- alongside the audio, see VoiceNoteRecorder), so this stores something we
-- already have rather than adding a transcription pass. Nullable, because a
-- clip recorded before this column existed has none and an empty string is not
-- the same statement as "we never captured one".
--
-- On the bio row rather than in observations: it is a verbatim caption for one
-- piece of audio, not something Amber knows about a person. It is served to
-- anyone who may HEAR the clip and to nobody else -- the same connection rule,
-- read the same way, because a transcript is the words in the recording and
-- must not be readable by somebody who is not allowed to play it.

ALTER TABLE profile_voice_bios ADD COLUMN IF NOT EXISTS transcript text;
