-- superset of what the passthrough route is permitted to write. All Clay
-- values arrive as strings (the route does no numeric coercion), so every
-- payload column is typed STRING; downstream ETL casts as needed.
--
-- row_id is the dedupe key (also passed as the streaming insertId). For
-- durable long-window dedup, read through a view that keeps the latest row
-- per row_id, e.g.:
--   SELECT * FROM (
--     SELECT *, ROW_NUMBER() OVER (PARTITION BY row_id ORDER BY _imported_at DESC) rn
--     FROM `togari_data_lake.companies`
--   ) WHERE rn = 1;
--
-- IF NOT EXISTS: safe no-op if the tables were already created out-of-band.

