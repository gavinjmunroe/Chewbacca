-- ============================================================================
-- EMAIL AS A RELATIONSHIP SIGNAL.
--
-- Amber already knows who you meet, because calendar attendees resolve through
-- the identity resolver and land in event_participants. It has never known who
-- you WRITE to, even though the Google grant has carried gmail scope since the
-- OAuth consent screen was built. This is the other half.
--
-- THE POINT IS NOT TO STORE EMAIL. It is to store the shape of a
-- correspondence: who, when, how often, across which of your accounts. No
-- subject lines, no bodies, no snippets. A message is a timestamp and a list of
-- people, and that is all that is needed to answer "how close are these two".
-- Content analysis, when it is switched on, writes facts into observations like
-- every other content path; it does not land here.
--
-- ONE MESSAGE IS ONE ROW, HOWEVER MANY ACCOUNTS SAW IT. If somebody connects a
-- work Gmail and a personal Gmail and is CC'd on the same thread in both, that
-- is one exchange, not two, and counting it twice would inflate exactly the
-- number the whole feature exists to get right. RFC822 Message-ID is globally
-- unique by construction and is generated by the SENDER, so it is the same
-- string in both mailboxes -- which makes it the natural dedupe key and the
-- reason it is the primary key here.
--
-- WHICH ACCOUNTS SAW IT IS KEPT ANYWAY, as an array on the message. "You and
-- Sagar are in touch across two of your accounts" is a real signal about how
-- entangled a relationship is, and it is lost if dedupe just discards the
-- second sighting.
-- ============================================================================

BEGIN;

CREATE TABLE IF NOT EXISTS email_messages (
  owner_id     uuid        NOT NULL REFERENCES users (amber_id) ON DELETE CASCADE,

  -- The sender's own RFC822 Message-ID, angle brackets stripped. Unique across
  -- the internet by construction, identical in every mailbox that received the
  -- message, which is what makes cross-account dedupe free.
  message_id   text        NOT NULL,

  -- Provider thread id. Gmail's, for now. Only used to group, never to dedupe:
  -- two accounts thread the same conversation under different ids.
  thread_id    text,

  occurred_at  timestamptz NOT NULL,

  -- Whether the owner sent it. Outbound is the stronger signal -- anyone can
  -- be emailed, writing back is a choice -- and the scorer can weight it.
  direction    text        NOT NULL CHECK (direction IN ('inbound', 'outbound')),

  -- Every connected account that has this message in its mailbox. An array
  -- rather than a join table: it is read on every stats refresh, written once,
  -- and never queried from the account side.
  seen_accounts uuid[]     NOT NULL DEFAULT '{}',

  created_at   timestamptz NOT NULL DEFAULT now(),

  PRIMARY KEY (owner_id, message_id)
);

-- The stats refresh reads this owner's messages by time. Nothing reads by
-- message_id alone, so the primary key is the only other index needed.
CREATE INDEX IF NOT EXISTS email_messages_owner_at_idx
  ON email_messages (owner_id, occurred_at DESC);

-- ---------------------------------------------------------------------------
-- WHO WAS ON THE MESSAGE.
--
-- Every address on From/To/Cc, resolved through the SAME identity resolver that
-- places an Apple card or a Clay push. That is what makes "I email Sagar and I
-- text Sagar" one contact rather than two: the address is an identity key, and
-- the resolver has always matched on those.
--
-- The owner's own addresses are not participants. A row for yourself on every
-- message you have ever sent is several hundred thousand rows that mean
-- nothing, and it would make you the most-interacted-with contact in your own
-- address book.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS email_participants (
  owner_id   uuid NOT NULL,
  message_id text NOT NULL,
  contact_id uuid NOT NULL,

  -- from/to/cc. A direct recipient is a stronger signal than one of forty on a
  -- CC line, and the scorer can say so.
  role       text NOT NULL DEFAULT 'to' CHECK (role IN ('from', 'to', 'cc')),

  PRIMARY KEY (owner_id, message_id, contact_id),

  CONSTRAINT email_participants_message_fk
    FOREIGN KEY (owner_id, message_id)
    REFERENCES email_messages (owner_id, message_id) ON DELETE CASCADE,

  -- The composite FK every contact-owned table in this schema uses, so a merge
  -- repoints these rows like everything else and delete-my-account cascades.
  CONSTRAINT email_participants_owner_contact_fk
    FOREIGN KEY (owner_id, contact_id)
    REFERENCES contacts (owner_id, id) ON DELETE CASCADE
);

-- The direction the rollup reads: every message a given contact was on.
CREATE INDEX IF NOT EXISTS email_participants_contact_idx
  ON email_participants (owner_id, contact_id);

-- ---------------------------------------------------------------------------
-- HOW OFTEN, BY CHANNEL.
--
-- contact_interaction_stats already answers "how much contact, in total" and is
-- what the ranker reads. It cannot answer "we meet weekly but never email",
-- because the stream it is built from throws the channel away.
--
-- This keeps the same windows so the two can be compared without a conversion,
-- and adds `accounts`: how many of the owner's connected accounts this channel
-- touches them through. That is the "across two email accounts" signal.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS contact_channel_stats (
  owner_id      uuid        NOT NULL,
  contact_id    uuid        NOT NULL,

  -- email / calendar / message / note. Open text rather than an enum: a new
  -- channel should not need a migration to start being counted, and an
  -- unrecognized value here is a row nobody reads rather than a failed write.
  channel       text        NOT NULL,

  first_at      timestamptz,
  last_at       timestamptz,
  count_30d     integer     NOT NULL DEFAULT 0,
  count_90d     integer     NOT NULL DEFAULT 0,
  count_all     integer     NOT NULL DEFAULT 0,

  -- Distinct connected accounts of the owner's that carry this relationship on
  -- this channel.
  accounts      integer     NOT NULL DEFAULT 0,

  computed_at   timestamptz NOT NULL DEFAULT now(),

  PRIMARY KEY (owner_id, contact_id, channel),
  CONSTRAINT ccs_owner_contact_fk FOREIGN KEY (owner_id, contact_id)
    REFERENCES contacts (owner_id, id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS ccs_recency_idx
  ON contact_channel_stats (owner_id, channel, last_at DESC);

-- ---------------------------------------------------------------------------
-- MAIL SYNC BOOKKEEPING, PER CONNECTED ACCOUNT.
--
-- calendar_accounts already holds one row per connected Google or Microsoft
-- account WITH ITS OWN TOKENS, and the Google consent screen grants calendar
-- and gmail together -- so the credential needed to read mail is already in
-- that row. Duplicating tokens into a mail_accounts table would mean two copies
-- of one secret drifting apart on refresh, which is a worse problem than a
-- table whose name is now slightly narrow.
--
-- So mail sync state hangs off that row instead.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS mail_sync_state (
  account_id      uuid PRIMARY KEY
    REFERENCES calendar_accounts (id) ON DELETE CASCADE,
  owner_id        uuid        NOT NULL REFERENCES users (amber_id) ON DELETE CASCADE,

  -- Gmail's incremental cursor. With it, a refresh asks "what changed since"
  -- rather than re-listing a mailbox with four hundred thousand messages in it.
  history_id      text,

  -- How far back the first full sync reached, so a later backfill knows where
  -- to resume instead of starting again.
  backfilled_to   timestamptz,

  last_synced_at  timestamptz,
  last_error      text,
  last_error_at   timestamptz,

  -- OFF UNTIL THE PERSON SAYS OTHERWISE, per account. Headers alone need no
  -- further consent than connecting the account did; reading bodies is a
  -- different promise, and it is made one mailbox at a time rather than once
  -- for all of them.
  read_contents   boolean     NOT NULL DEFAULT false,

  created_at      timestamptz NOT NULL DEFAULT now(),
  updated_at      timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS mail_sync_state_owner_idx ON mail_sync_state (owner_id);

COMMIT;
