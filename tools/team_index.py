#!/usr/bin/env python3
"""The compact team memory index that loads into every teammate's session.

WHY. team/memory/MEMORY.md was the largest single thing a session loaded:
11,636 tokens in the 2026-10-11 transcript, ahead of CLAUDE.md, for 258
pointer lines. Most of that is the hook after each project and reference
slug, a summary of a fact the brain-recall hook already surfaces by meaning
when a prompt touches it.

WHAT IT KEEPS. Every slug, so the index still says what exists. Every lesson
(`feedback_`) line whole, because a lesson's hook is the rule itself and a
rule that loads only on a lucky recall is a rule lost. Every heading and the
preamble, which carries the line that personal memory never goes here.
Project and reference lines keep only their slug; the full line stays in the
source, one grep away.

  python3 tools/team_index.py write [--src FILE] [--dst FILE]   write if changed
  python3 tools/team_index.py print [--src FILE]                to stdout
"""

import argparse
import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "team/memory/MEMORY.md"
POINTER = re.compile(r"^- (\S+?):\s")
KEEP_WHOLE = ("feedback_",)


def default_dst():
    home = Path(os.environ.get("CHEWBACCA_HOME", str(Path.home() / ".chewbacca"))).expanduser()
    return home / "team-memory-index.md"


def compact(text, src=SRC):
    out = [
        "<!-- Generated by tools/team_index.py from team/memory/MEMORY.md. Do not edit. -->",
        f"Compact team index: lessons whole, other notes by slug. Full hooks: `{src}`;"
        f" each slug is `{src.parent}/<slug>.md`. Add new lines to the full index, never here.",
        "",
    ]
    for line in text.splitlines():
        m = POINTER.match(line)
        if m and not m.group(1).startswith(KEEP_WHOLE):
            out.append(f"- {m.group(1)}")
        else:
            out.append(line)
    # Blank runs left behind by the source's spacing between sections.
    return re.sub(r"\n{3,}", "\n\n", "\n".join(out)).strip() + "\n"


def write(src=SRC, dst=None):
    """Write the compact index; return True when the file changed."""
    dst = Path(dst or default_dst())
    body = compact(Path(src).read_text(encoding="utf-8"), Path(src))
    try:
        if dst.read_text(encoding="utf-8") == body:
            return False
    except OSError:
        pass
    dst.parent.mkdir(parents=True, exist_ok=True)
    tmp = dst.with_name(dst.name + ".tmp")
    tmp.write_text(body, encoding="utf-8")
    tmp.replace(dst)
    return True


def main(argv=None):
    ap = argparse.ArgumentParser(description="Compact team memory index.")
    ap.add_argument("cmd", choices=("write", "print"))
    ap.add_argument("--src", default=str(SRC))
    ap.add_argument("--dst")
    a = ap.parse_args(argv)
    if a.cmd == "print":
        sys.stdout.write(compact(Path(a.src).read_text(encoding="utf-8"), Path(a.src)))
        return 0
    changed = write(Path(a.src), a.dst)
    print(("wrote " if changed else "unchanged ") + str(a.dst or default_dst()))
    return 0


if __name__ == "__main__":
    sys.exit(main())
